#!/usr/bin/env python3
"""Generate src/harness/teleport_districts.inc: which district each world locator is in.

The game's locator files are grouped by district under
<game>/data/content/global_locators/<group>/DIST_<District>/*.rx2 and carry the
locator names as strings. A teleport across maps needs the destination's map
key (the pause map passes it to the teleport service), and the key belongs to
the district.

  locator_districts.py GAME_DATA_ROOT [--names out/re/locators.tsv]

Only names that are registry locators (from registry.py's export) are kept, so
stray strings in the files don't leak in.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from registry import name_hash  # noqa: E402

OUT = REPO / "src/harness/teleport_districts.inc"


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("game_root", type=Path, help="the game dump (has data/content/global_locators)")
    p.add_argument("--names", type=Path, default=REPO / "out/re/locators.tsv")
    a = p.parse_args()

    known = set()
    for line in a.names.read_text().splitlines():
        if line and not line.startswith("#"):
            known.add(line.split("\t", 1)[0])
    root = a.game_root / "data/content/global_locators"
    district_of: dict[str, str] = {}
    for f in sorted(root.rglob("*.rx2")):
        dist = next((part for part in f.parts if part.startswith("DIST_")), None)
        if not dist:
            continue
        for m in re.finditer(rb"[A-Za-z0-9_]{3,80}", f.read_bytes()):
            name = m.group().decode()
            if name in known:
                district_of.setdefault(name, dist[len("DIST_"):])
    rows = sorted((name_hash(n.encode()), n, d) for n, d in district_of.items())
    with OUT.open("w") as out:
        out.write("// Generated by tools/re/locator_districts.py from the game's locator files.\n")
        out.write("// {name hash (sub_8296EA10), district}, sorted by hash.\n")
        for h, n, d in rows:
            out.write(f'{{0x{h:08X}u, "{d}"}},  // {n}\n')
    by = {}
    for _, _, d in rows:
        by[d] = by.get(d, 0) + 1
    print(f"{len(rows)} locators -> {OUT.relative_to(REPO)}: " +
          ", ".join(f"{d} {c}" for d, c in sorted(by.items())))
    missing = sorted(n for n in known if n not in district_of)
    print(f"{len(missing)} registry locators not found in any district file", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
