#!/usr/bin/env python3
"""Generate src/harness/teleport_spots.inc from docs/teleport-locations.md.

The vetted locators (name and position) are the stepping stones a coordinate
teleport (`teleport pos = [...]`) hops to first when the target is far from
the skater: the locator teleport loads and streams the area, and the short
hop that follows lands on collision that is already there.

Usage: tools/re/teleport_spots.py   (rewrites the .inc in place)
"""
import pathlib
import re

REPO = pathlib.Path(__file__).resolve().parents[2]
DOC = REPO / "docs/teleport-locations.md"
OUT = REPO / "src/harness/teleport_spots.inc"

ROW = re.compile(r"^\| `(?P<name>[^`]+)` \| (?P<district>\w+) \| "
                 r"(?P<x>-?[\d.]+), (?P<y>-?[\d.]+), (?P<z>-?[\d.]+) \|")


def main() -> None:
    rows = []
    for line in DOC.read_text(encoding="utf-8").splitlines():
        m = ROW.match(line)
        if m:
            rows.append(m)
    if not rows:
        raise SystemExit(f"no locator rows found in {DOC}")
    lines = [
        "// Generated by tools/re/teleport_spots.py from docs/teleport-locations.md.",
        "// {locator name, x, y, z}: the vetted teleport locations.",
    ]
    for m in rows:
        lines.append(f'{{"{m["name"]}", {m["x"]}f, {m["y"]}f, {m["z"]}f}},')
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(REPO)}: {len(rows)} locations")


if __name__ == "__main__":
    main()
