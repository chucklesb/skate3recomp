#!/usr/bin/env python3
"""Write the native-only tour scenarios (docs/native-only.md, phase 0).

    gen_native_tour.py            # writes scenarios/native_tour.toml and
                                  # scenarios/native_tour_boot.toml

native_tour visits, from one signed-in demo boot, every context where the
game's own (emulated) renderer may still run, with the pass census on:
free skate; a challenge (Challenge Map > Photo > Dozer Grind > Sign up: the
loading screen, the intro, the running challenge, then Quit); the pause
menu; the team screen; Create-a-Skater with an accepted edit (a hat on, then
off again, so the profile ends as it started; each exit saves it and
regenerates the skater photo); Import Skater; the replay editor with Take
Photo (declined); My Replays; a career photo in the photo viewer (FE 36).
native_tour_boot is a normal boot through the intro movies to the title
screen.

Not reached by script (see docs/native-only.md): a photo challenge's shutter
and photo screens (needs the trick landed) and the career "new team member"
prompt.

Summarise a run with: census_report.py <run> --audit-only
Menu routes: .claude/skills/harness/SKILL.md, "Menu navigation".
"""
from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parents[2]

HEADER = """# GENERATED by tools/harness/gen_native_tour.py - edit that, not this file.
{doc}
name = "{name}"
timeout_s = {timeout}
boot = "{boot}"
state_every_frames = 10

[cvars]
skate3_demo_path_signed_in = true
skate3_guest_fps_cap = 30.0
skate3_guest_fps_cap_auto = false
native_render_pass_census = true
"""


class Steps:
    def __init__(self) -> None:
        self.out: list[str] = []

    def add(self, **kv) -> None:
        def val(v):
            if isinstance(v, bool):
                return "true" if v else "false"
            if isinstance(v, str):
                return f'"{v}"'
            return str(v)

        body = "\n".join(f"{k} = {val(v)}" for k, v in kv.items())
        self.out.append(f"[[step]]\n{body}\n")

    def comment(self, text: str) -> None:
        self.out.append(f"# {text}\n")

    def wait(self, frames: int) -> None:
        self.add(do="wait", frames=frames)

    def press(self, button: str, settle: int = 30) -> None:
        self.add(do="input", buttons=button, frames=4)
        self.wait(settle)

    def stick(self, axis: str, value: float, times: int = 1, settle: int = 20) -> None:
        for _ in range(times):
            self.add(do="input", **{axis: value}, frames=4)
            self.wait(settle)

    def down(self, times: int = 1) -> None:
        self.stick("ly", -1.0, times)

    def right(self, times: int = 1) -> None:
        self.stick("lx", 1.0, times, settle=30)

    def shot(self, tag: str, dwell: int = 150) -> None:
        """Screenshot, then stay so the context gets census intervals."""
        self.add(do="screenshot", tag=tag)
        self.wait(dwell)


def cas_edit(s: Steps, hat_on: bool, tag: str) -> None:
    """From the team screen (Edit Skater selected): Create-a-Skater >
    Merchandise > Hats, pick the first hat (on) or the empty first cell
    (off), accept, leave with Yes (saves, regenerates the skater photo)."""
    s.press("a", 120)  # Edit Skater -> Create-a-Skater
    s.down()  # Merchandise
    s.press("a")
    s.press("a")  # Hats
    if hat_on:
        s.right(2)
    s.press("a")
    s.shot(f"{tag}_cas", 60)
    if hat_on:
        s.press("a")  # Edit Clothing: accept
    s.press("b")
    s.press("b")
    s.press("a", 150)  # "Are you finished editing?" -> Yes
    s.shot(f"{tag}_team")


def tour() -> str:
    s = Steps()
    s.add(do="wait", gameplay=True, timeout_s=400)
    s.wait(150)
    s.shot("free_skate", 300)

    s.comment("Challenge: Challenge Map > Photo > Dozer Grind > Sign up, then Quit.")
    s.press("start", 60)
    s.press("a", 150)  # Challenge Map (FE 17)
    s.down(3)  # Photo
    s.press("a", 60)
    s.press("a", 60)  # Dozer Grind
    s.press("a", 600)  # Sign up: teleport, loading, intro (FE 1)
    s.shot("challenge_intro")
    s.press("a", 150)  # skip the intro: the challenge runs (FE [0])
    s.shot("challenge_running", 300)
    s.press("start", 90)
    s.down(2)  # Quit Challenge
    s.press("a", 60)
    s.down()  # Yes
    s.press("a", 300)
    s.shot("challenge_quit")

    s.comment("Pause menu, team screen, Create-a-Skater (hat on, then off), Import Skater.")
    s.press("start", 60)
    s.shot("pause")
    s.down()  # Edit Skaters
    s.press("a", 120)
    s.shot("team")
    cas_edit(s, True, "helmet")
    cas_edit(s, False, "plain")
    s.down(2)  # Import Skater
    s.press("a", 90)
    s.shot("import", 300)
    s.press("b", 60)
    s.press("b", 60)  # back to the pause menu

    s.comment("Create tab: replay editor with Take Photo (declined), then Exit.")
    s.right(2)
    s.press("a", 240)  # Replay Editor (FE 12)
    s.shot("editor")
    s.press("x", 150)  # Take Photo -> "Save Photo?"
    s.shot("take_photo", 60)
    s.press("a", 90)  # No
    s.press("b", 90)  # Finished
    s.down(2)  # Exit
    s.press("a", 240)

    s.comment("skate.Reel: My Replays, then My Photos > Career Photos > the first photo.")
    s.down()  # skate.Reel
    s.press("a", 60)
    s.press("a", 120)  # My Replays (FE 59)
    s.shot("my_replays")
    s.press("b", 60)  # back to the pause menu, skate.Reel still selected
    s.press("a", 60)
    s.down()  # My Photos
    s.press("a", 150)
    s.press("rb", 90)  # Career Photos
    s.press("a", 150)  # the first photo (FE 36)
    s.shot("photo_view", 300)
    s.press("b", 60)
    s.press("b", 60)  # back to the pause menu
    s.press("b", 150)  # close it
    s.shot("end")
    return "".join(s.out)


def boot_tour() -> str:
    s = Steps()
    for i in range(6):
        s.add(do="wait", ms=8000)
        s.add(do="screenshot", tag=f"boot_{i}")
    return "".join(s.out)


def main() -> int:
    out = REPO / "scenarios"
    lines = __doc__.strip().splitlines()
    start = next(i for i, line in enumerate(lines) if line.startswith("native_tour visits"))
    end = lines.index("", start)
    doc = "\n".join("# " + line for line in lines[start:end])
    (out / "native_tour.toml").write_text(
        HEADER.format(doc=doc, name="native_tour", timeout=1200, boot="demo") + "\n" + tour())
    (out / "native_tour_boot.toml").write_text(
        HEADER.format(doc="# A normal boot through the intro movies (native_tour's boot part).",
                      name="native_tour_boot", timeout=200, boot="none") + "\n" + boot_tour())
    print("wrote scenarios/native_tour.toml, scenarios/native_tour_boot.toml")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
